/**
 * 별자리 지문(docs/36 11-2): 공개 열쇠로 정해지는 그림. 영수증과 증명 확인 화면에 같은 그림이 떠
 * 눈으로 맞춰 본다. 복사돼도 증명을 만들 수 없어 보여 줘도 된다. 그리기는 화면 몫이고 여기는 재료만 낸다.
 *
 * 규칙(사용자에게 보인 시안 그대로):
 * - h = SHA-256("bybtto-star" ‖ 공개 열쇠 65바이트), b = h ‖ SHA-256(h) (64바이트)
 * - 그림 = FIGURES[b[0] & 15](꺾은선 묶음, 0~10 칸 좌표), 앞말·색 = TINTS[(b[0] >> 4) & 7],
 *   좌우 뒤집기 = b[0] >> 7, 기울기 = (b[1] / 255 - 0.5) × 0.45 라디안
 * - b[2]부터 한 바이트씩 읽는다(64바이트를 넘으면 처음부터 다시):
 *   1. 꼭짓점(같은 좌표는 하나, 처음 나온 순서)마다 흔들림 x, y 각각 (바이트 / 255 - 0.5) × 0.35
 *   2. 밝은 별 7개: 꼭짓점 중 (바이트 % 꼭짓점 수)번째, 이미 고른 것은 건너뜀
 *   3. 번호 7개: 바이트 < 225만 써서 (바이트 % 45) + 1, 이미 나온 번호는 건너뜀
 * - 좌표 변환: 가운데(5, 5)를 0으로 옮기고 흔들림 → 뒤집기 → 기울기 → 0.5 + 값 × 0.085 (0~1)
 * - 이름 = 앞말 + " " + 그림 이름 + "자리" (예: "푸른 고래자리")
 */

type Stroke = (readonly [number, number])[];

export interface StarPoint {
  x: number;
  y: number;
}

export interface Constellation {
  /** 그림 이름(예: "고래") */
  figure: string;
  /** 앞말(예: "푸른") */
  tint: string;
  /** 선 색 */
  color: string;
  /** "푸른 고래자리" */
  name: string;
  /** 꺾은선마다 점 목록(0~1 좌표) */
  lines: StarPoint[][];
  /** 밝은 별 7개와 그 별의 번호(1~45) */
  stars: (StarPoint & { n: number })[];
  /** 나머지 꼭짓점 */
  faint: StarPoint[];
  /** 배경 잔별용 씨앗(b[63]) */
  seed: number;
}

