const BRIGHT_STARS = 7;
const ACCEPT_BELOW = Math.floor(256 / MAX_NUMBER) * MAX_NUMBER;

export function constellation(publicKey: Uint8Array): Constellation {
  const h = sha256(utf8("bybtto-star"), publicKey);
  const b = concat(h, sha256(h));
  let i = 2;
  const next = () => b[i++ % b.length] as number;
  const b0 = b[0] as number;
  const [figure, strokes] = FIGURES[b0 & 15] as readonly [string, Stroke[]];
  const [tint, color] = TINTS[(b0 >> 4) & 7] as readonly [string, string];
  const flip = (b0 >> 7) & 1;
  const angle = ((b[1] as number) / 255 - 0.5) * 0.45;

  // 꼭짓점(같은 좌표는 하나로)마다 열쇠에서 정한 작은 흔들림
  const keyOf = (p: readonly [number, number]) => `${p[0]},${p[1]}`;
  const points = new Map<string, readonly [number, number]>();
  for (const s of strokes)
    for (const p of s) if (!points.has(keyOf(p))) points.set(keyOf(p), p);
  const place = new Map<string, StarPoint>();
  for (const [k, [x0, y0]] of points) {
    let x = x0 - 5 + (next() / 255 - 0.5) * 0.35;
    const y = y0 - 5 + (next() / 255 - 0.5) * 0.35;
    if (flip) x = -x;
    const rx = x * Math.cos(angle) - y * Math.sin(angle);
    const ry = x * Math.sin(angle) + y * Math.cos(angle);
    place.set(k, { x: 0.5 + rx * 0.085, y: 0.5 + ry * 0.085 });
  }

  const keys = [...place.keys()];
  const bright: string[] = [];
  while (bright.length < Math.min(BRIGHT_STARS, keys.length)) {
    const k = keys[next() % keys.length] as string;
    if (!bright.includes(k)) bright.push(k);
  }
  const numbers: number[] = [];
  // 64바이트를 되풀이해 읽으므로, 서로 다른 번호가 모자라면 끝나지 않는다(사실상 없는 일). 안전장치
  for (let guard = 0; numbers.length < bright.length; guard++) {
    if (guard > 64 * 64) throw new Error("별자리 번호를 정하지 못했다");
    const v = next();
    if (v >= ACCEPT_BELOW) continue;
    const n = (v % MAX_NUMBER) + 1;
    if (!numbers.includes(n)) numbers.push(n);
  }

  const at = (k: string) => place.get(k) as StarPoint;
  return {
    figure,
    tint,
    color,
    name: `${tint} ${figure}자리`,
    lines: strokes.map((s) => s.map((p) => at(keyOf(p)))),
    stars: bright.map((k, j) => ({ ...at(k), n: numbers[j] as number })),
    faint: keys.filter((k) => !bright.includes(k)).map(at),
    seed: b[63] as number,
  };
}
